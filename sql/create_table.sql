    CONSTRAINT fk_payment_loan
        FOREIGN KEY (loanid)
        REFERENCES loan(loanid),

    CONSTRAINT fk_payment_schedule
        FOREIGN KEY (loanid, scheduleid)
        REFERENCES repayment_schedule(loanid, scheduleid),

    CONSTRAINT fk_payment_employee
        FOREIGN KEY (employeeid)
        REFERENCES employee(employeeid),

    CONSTRAINT fk_payment_transaction
        FOREIGN KEY (transactionid)
        REFERENCES bank_transaction(transactionid),

    CONSTRAINT ck_payment_amount
        CHECK (amountpaid > 0),

    CONSTRAINT ck_payment_principal
        CHECK (principalpaid >= 0),

    CONSTRAINT ck_payment_interest
        CHECK (interestpaid >= 0),

    CONSTRAINT ck_payment_penalty
        CHECK (penaltyfee >= 0),

    CONSTRAINT ck_payment_total
        CHECK (
            amountpaid =
            principalpaid + interestpaid + penaltyfee
        ),

    CONSTRAINT ck_payment_channel
        CHECK (paymentchannel IN ('Counter','Account','Online')),

    CONSTRAINT ck_payment_employee
        CHECK (
            (paymentchannel = 'Counter' AND employeeid IS NOT NULL)
            OR
            (paymentchannel IN ('Account','Online') AND employeeid IS NULL)
        )
);


