    accountholderid   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accountid         BIGINT NOT NULL,
    customerid        BIGINT NOT NULL,
    holdertype        VARCHAR(30) NOT NULL,
    startdate         DATE NOT NULL,
    enddate           DATE,
    status            VARCHAR(20) NOT NULL DEFAULT 'Active',

    CONSTRAINT fk_holder_account
        FOREIGN KEY (accountid)
        REFERENCES bank_account(accountid),

    CONSTRAINT fk_holder_customer
        FOREIGN KEY (customerid)
        REFERENCES customer(customerid),

    CONSTRAINT ck_holder_type
        CHECK (holdertype IN (
            'PRIMARY_OWNER',
            'JOINT_OWNER',
            'AUTHORIZED_USER'
        )),

    CONSTRAINT ck_holder_status
        CHECK (status IN ('Active','Inactive')),

    CONSTRAINT ck_holder_dates
        CHECK (
            (status = 'Active' AND enddate IS NULL)
            OR
            (status = 'Inactive'
             AND enddate IS NOT NULL
             AND enddate >= startdate)
        )
);

CREATE UNIQUE INDEX ux_account_holder_active
ON account_holder(accountid, customerid)
WHERE status = 'Active';

CREATE UNIQUE INDEX ux_account_primary_owner
ON account_holder(accountid)
WHERE status = 'Active'
AND holdertype = 'PRIMARY_OWNER';


