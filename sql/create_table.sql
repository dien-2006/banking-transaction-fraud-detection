    label               VARCHAR(20) NOT NULL,
    labeledat           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    labelsource         VARCHAR(50) NOT NULL,
    note                VARCHAR(255),

    CONSTRAINT fk_fraud_label_transaction
        FOREIGN KEY (transactionid)
        REFERENCES bank_transaction(transactionid),

    CONSTRAINT ck_fraud_label
        CHECK (label IN (
            'FRAUD',
            'LEGITIMATE',
            'UNKNOWN'
        ))
);


-- ============================================================
-- 27. EVENT_OUTBOX
-- ============================================================

CREATE TABLE event_outbox (
    eventoutboxid    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eventkey         VARCHAR(100) NOT NULL UNIQUE,
    aggregatetype    VARCHAR(50) NOT NULL,
    aggregateid      VARCHAR(100) NOT NULL,
    eventtype        VARCHAR(100) NOT NULL,
    payloadjson      JSONB NOT NULL,
    createdat        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    publishedat      TIMESTAMP,
    status           VARCHAR(20) NOT NULL DEFAULT 'PENDING',

    CONSTRAINT ck_event_outbox_status
        CHECK (status IN ('PENDING','PUBLISHED','FAILED')),

    CONSTRAINT ck_event_outbox_time
        CHECK (publishedat IS NULL OR publishedat >= createdat)
);


-- ============================================================
-- 28. NOTIFICATION_OUTBOX
-- ============================================================

CREATE TABLE notification_outbox (
    notificationoutboxid   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customerid              BIGINT NOT NULL,
    transactionid           BIGINT,
    notificationtype        VARCHAR(50) NOT NULL,
    status                  VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    createdat               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sentat                  TIMESTAMP,

    CONSTRAINT fk_notification_customer
        FOREIGN KEY (customerid)
        REFERENCES customer(customerid),

    CONSTRAINT fk_notification_transaction
        FOREIGN KEY (transactionid)
        REFERENCES bank_transaction(transactionid),

    CONSTRAINT ck_notification_status
        CHECK (status IN ('PENDING','SENT','FAILED')),

    CONSTRAINT ck_notification_time
        CHECK (sentat IS NULL OR sentat >= createdat)
);


-- ============================================================
-- 29. AUDIT_LOG
-- ============================================================

CREATE TABLE audit_log (
    auditid        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid         INTEGER,
    entitytype     VARCHAR(50) NOT NULL,
    entityid       VARCHAR(100) NOT NULL,
    action         VARCHAR(30) NOT NULL,
    oldvalue       JSONB,
    newvalue       JSONB,
    createdat      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ipaddress      VARCHAR(45),

    CONSTRAINT fk_audit_user
        FOREIGN KEY (userid)
        REFERENCES system_user(userid),

    CONSTRAINT ck_audit_action
        CHECK (action IN (
            'INSERT',
            'UPDATE',
            'DELETE',
            'STATUS_CHANGE'
        )),

    CONSTRAINT ck_audit_values
        CHECK (
            (action = 'INSERT'
                AND oldvalue IS NULL
                AND newvalue IS NOT NULL)
            OR
            (action = 'DELETE'
                AND oldvalue IS NOT NULL
                AND newvalue IS NULL)
            OR
            (action IN ('UPDATE','STATUS_CHANGE')
                AND oldvalue IS NOT NULL
                AND newvalue IS NOT NULL)
        )
);


