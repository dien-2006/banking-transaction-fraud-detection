-- ============================================================
-- 1. BRANCH
-- ============================================================

CREATE TABLE branch (
    branchid       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branchcode     VARCHAR(20) NOT NULL UNIQUE,
